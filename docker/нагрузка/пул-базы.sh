#!/usr/bin/env bash
# Ищет ПОРОГ, с которого хаб начинает отвечать 500 на маршрутах, ходящих в базу,
# и проверяет, чинится ли он сам после снятия нагрузки.
#
# Запускается НА ГЕНЕРАТОРЕ (не на сервере стенда). Ступени идут по возрастанию, каждая —
# один залп из N ОДНОВРЕМЕННЫХ запросов: важна не длительность, а то, сколько запросов
# стоит в очереди к пулу из десяти соединений одновременно.
#
#   ./пул-базы.sh / 5 10 20 30 40 60          # главная, ступени
#   ./пул-базы.sh /api/v1/pools/public/packages 10 30 60
#
# Адрес стенда обязателен и нигде не зашит: HUB=http://<адрес>:3333 либо строка HUB=…
# в файле цель.env рядом со скриптом (тот же файл читает нагрузить.sh).
#
# Пул соединений в хабе — 10, жёстко; предел ожидания — 30 000 мс, из настроек
# недостижим. Поэтому ступень выше десяти обязана рано или поздно дать отказы.
#
# Функции по-русски, переменные латиницей: кириллицу в именах переменных bash не берёт.
set -eu

ROUTE="${1:?путь, например /}"
shift

DIR="${DIR:-$(cd "$(dirname "$0")" && pwd)}"
# shellcheck disable=SC1091
[ -f "$DIR/цель.env" ] && . "$DIR/цель.env"
HUB="${HUB:?укажи адрес стенда: HUB=http://<адрес>:3333 — или положи строку HUB=… в цель.env рядом со скриптом}"

OUT="$DIR/итоги/пул-базы"
WAIT_BETWEEN="${WAIT_BETWEEN:-45}"
CURL_MAX="${CURL_MAX:-120}"

mkdir -p "$OUT"
SAFE=$(printf '%s' "$ROUTE" | tr '/?=&' '____')
SUM="$OUT/сводка$SAFE.txt"
: > "$SUM"

echo "маршрут $ROUTE, ступени: $*" | tee -a "$SUM"

# Самочувствие между ступенями: отпустило хаб или он остался отравленным.
самочувствие() {
	printf 'после ступени %-4s: /ready=%s  /=%s  api=%s\n' "$1" \
		"$(curl -s -o /dev/null -w '%{http_code}:%{time_total}' -m 30 "$HUB/ready")" \
		"$(curl -s -o /dev/null -w '%{http_code}:%{time_total}' -m 30 "$HUB/")" \
		"$(curl -s -o /dev/null -w '%{http_code}:%{time_total}' -m 30 "$HUB/api/v1/pools")"
}

for N in "$@"; do
	F="$OUT/ступень-$N$SAFE.txt"
	: > "$F"
	echo "--- ступень $N: $N одновременных запросов, $(date -u +%H:%M:%SZ) ---" | tee -a "$SUM"

	I=0
	while [ "$I" -lt "$N" ]; do
		I=$((I + 1))
		curl -s -o /dev/null -w "%{http_code} %{time_total}\n" -m "$CURL_MAX" "$HUB$ROUTE" >> "$F" 2>&1 &
	done
	wait

	OK=$(grep -c '^200' "$F" || true)
	E500=$(grep -c '^500' "$F" || true)
	E000=$(grep -c '^000' "$F" || true)
	MAXT=$(awk '{print $2}' "$F" | sort -n | tail -1)
	MEDT=$(awk '{print $2}' "$F" | sort -n | awk '{a[NR]=$1} END {print a[int(NR/2)+1]}')
	printf 'ступень %-4s → 200: %-4s 500: %-4s таймаут клиента: %-4s медиана %s с, худший %s с\n' \
		"$N" "$OK" "$E500" "$E000" "$MEDT" "$MAXT" | tee -a "$SUM"

	# Пауза между ступенями: хаб должен успеть отпустить слоты, иначе следующая ступень
	# меряет хвост предыдущей, а не себя.
	sleep "$WAIT_BETWEEN"
	самочувствие "$N" | tee -a "$SUM"
done

echo "сводка: $SUM"

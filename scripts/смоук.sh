#!/usr/bin/env bash
#
# Смоук-прогон OpenHub: минимум, доказывающий, что хаб работает по назначению.
#
#   scripts/смоук.sh                 # прогнать смоук
#   scripts/смоук.sh --mode summary  # любые лишние аргументы уходят в oneunit execute
#
# Источник правды — тег: набор попадает в прогон, если в нём есть метод с `&Тег("смоук")`.
# Список файлов собирается здесь и никуда не выписывается — новый смоук-тест включается
# в прогон одной строкой тега, а не правкой этого скрипта.
#
# Почему по файлам, а не просто `oneunit execute -t смоук`: OneUnit не передаёт фильтр
# тегов в наборы с `&Изолированный(Уровень = "Процесс")`, и прямая команда исполняет их
# целиком — двадцать минут вместо минуты. Разбор — в docs/процесс/ЗНАНИЕ.md.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

# Якорь на начало строки: аннотация в исходнике стоит в первой колонке, а упоминание
# `&Тег(…)` внутри строкового литерала теста-образца — всегда после конкатенации.
# Через while-read, а не mapfile: в macOS штатный bash 3.2, mapfile там нет.
# Имена переменных латиницей — bash 3.2 кириллических не принимает.
SUITES=()
FILE_ARGS=()
while IFS= read -r suite; do
	SUITES+=("$suite")
	FILE_ARGS+=(-f "$suite")
done < <(grep -l '^&Тег("смоук")' tests/*.os | sort)

if [ "${#SUITES[@]}" -eq 0 ]; then
	echo "В tests/ нет ни одного метода с &Тег(\"смоук\") — прогонять нечего." >&2
	exit 1
fi

echo "== Смоук: ${#SUITES[@]} наборов по тегу"
printf '   %s\n' "${SUITES[@]}"
echo

exec oneunit execute -t смоук "${FILE_ARGS[@]}" "$@"
